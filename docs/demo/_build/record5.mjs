// Take 5: the Plugin page widget (no transactions), connected, widget in view from the first frame.
import path from "node:path";
import { launch, attachWallet, loadAccount, startCapture, click, hover, moveTo, smoothScroll, sleep, WORK } from "./rec-lib.mjs";
const APP = "https://kakushi.vercel.app";
const { browser, context } = await launch();
await attachWallet(context, loadAccount(), (t) => console.log("UNEXPECTED TX", t.hash));
const page = await context.newPage();
await page.goto(APP + "/send", { waitUntil: "domcontentloaded" });
await sleep(3000);
await page.locator("header").getByRole("button", { name: /^Connect/ }).first().click();
await sleep(500);
await page.getByText("Browser wallet").first().click();
await sleep(1000);
await page.locator("header").getByRole("link", { name: "Plugin", exact: true }).first().click();
await page.getByText("Try the widget").first().waitFor({ timeout: 20000 });
await page.evaluate(() => { const e = [...document.querySelectorAll("h2,h3,div,span")].find((n) => n.textContent?.trim() === "Try the widget"); if (e) window.scrollTo(0, e.getBoundingClientRect().top + window.scrollY - 70); });
await sleep(2500);
await page.mouse.move(1100, 300);
const cap = await startCapture(page, path.join(WORK, "take5.mp4"));
await sleep(800);
await hover(page, page.getByRole("button", { name: /Pay privately/ }).first(), 900);
await sleep(2500);
await hover(page, page.getByText(/KakushiPay/).first(), 900).catch(() => {});
await sleep(3000);
await smoothScroll(page, 430, 2000);
await sleep(4000);
await moveTo(page, 700, 600, 900);
await sleep(2500);
console.log("secs", await cap.stop());
await browser.close();
