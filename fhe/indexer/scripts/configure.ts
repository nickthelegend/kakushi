// Writes indexer/config.yaml and indexer/src/network.generated.ts from the deployment JSONs.
//
//   KAKUSHI_FHE_NETWORK=local   node scripts/configure.ts   # anvil fork of Monad testnet, RPC source
//   KAKUSHI_FHE_NETWORK=testnet node scripts/configure.ts   # Monad testnet, HyperSync (10143.hypersync.xyz)
//
// Inputs:  ../contracts/deployments/<network>.json       (oracle, executor, creForwarder, deployBlock)
//          ../contracts/deployments/<network>-apps.json  (Kakushi Pay tokens: causd, cusdc, ...)
// Env:     KAKUSHI_FHE_PAY_TOKENS   comma list of keys in <network>-apps.json to index (default "causd,cusdc")
//          KAKUSHI_FHE_RPC_URL      RPC used for the local source and for reading token metadata
//          KAKUSHI_FHE_START_BLOCK  override the start block
// Only eth_call reads are made (token symbol/decimals/underlying). No transactions.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const DEPLOY = fileURLToPath(new URL("../../contracts/deployments/", import.meta.url));
const network = process.env.KAKUSHI_FHE_NETWORK === "testnet" ? "testnet" : "local";
const rpcUrl = process.env.KAKUSHI_FHE_RPC_URL ?? (network === "local" ? "http://127.0.0.1:18810" : "https://testnet-rpc.monad.xyz");
const tokenKeys = (process.env.KAKUSHI_FHE_PAY_TOKENS ?? "causd,cusdc").split(",").map((s) => s.trim()).filter(Boolean);

const read = (f: string) => {
  const p = `${DEPLOY}${f}`;
  if (!existsSync(p)) throw new Error(`${p} not found. Deploy to ${network} first (see docs/DEPLOY-LATER.md), then re-run.`);
  return JSON.parse(readFileSync(p, "utf8"));
};
const dep = read(`${network}.json`);
const apps = read(`${network}-apps.json`);
const isAddr = (a: unknown): a is string => typeof a === "string" && /^0x[0-9a-fA-F]{40}$/.test(a);
for (const k of ["oracle", "executor"]) if (!isAddr(dep[k])) throw new Error(`${network}.json: missing ${k}`);

async function call(to: string, data: string): Promise<string | null> {
  try {
    const r = await fetch(rpcUrl, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_call", params: [{ to, data }, "latest"] }),
      signal: AbortSignal.timeout(8000),
    });
    const j = (await r.json()) as { result?: string };
    return j.result && j.result !== "0x" ? j.result : null;
  } catch {
    return null;
  }
}
const decodeString = (hex: string | null) => {
  if (!hex) return null;
  const b = Buffer.from(hex.slice(2), "hex");
  if (b.length < 64) return null;
  const len = Number(BigInt(`0x${b.subarray(32, 64).toString("hex")}`));
  return b.subarray(64, 64 + len).toString("utf8");
};
const decodeUint = (hex: string | null) => (hex ? Number(BigInt(hex.slice(0, 66))) : null);
const decodeAddr = (hex: string | null) => (hex ? `0x${hex.slice(26, 66)}` : null);

const tokens: { key: string; address: string; symbol: string; decimals: number; underlying: string; underlyingSymbol: string }[] = [];
for (const key of tokenKeys) {
  const address = apps[key];
  if (!isAddr(address)) {
    console.warn(`skip ${key}: not in ${network}-apps.json`);
    continue;
  }
  const symbol = decodeString(await call(address, "0x95d89b41")) ?? key;
  const decimals = decodeUint(await call(address, "0x313ce567")) ?? 6;
  const underlying = decodeAddr(await call(address, "0x6f307dc3")) ?? "0x0000000000000000000000000000000000000000";
  const underlyingSymbol = decodeString(await call(underlying, "0x95d89b41")) ?? "?";
  tokens.push({ key, address: address.toLowerCase(), symbol, decimals, underlying: underlying.toLowerCase(), underlyingSymbol });
}
if (!tokens.length) throw new Error("no Kakushi Pay token to index");

const startBlock = Number(process.env.KAKUSHI_FHE_START_BLOCK ?? dep.deployBlock ?? 0);
const source =
  network === "local"
    ? `    # local anvil fork: no HyperSync behind it, so the RPC is the sync source
    rpc:
      - url: ${rpcUrl}
        for: sync
        polling_interval: 500
        initial_block_interval: 500
        interval_ceiling: 2000
`
    : `    # Monad testnet is a native HyperSync chain (https://10143.hypersync.xyz): no rpc needed.
    # Set ENVIO_API_TOKEN (envio.dev/app/api-tokens) in the environment.
`;

const yaml = `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# GENERATED by scripts/configure.ts for KAKUSHI_FHE_NETWORK=${network}. Edit the script, not this file.
name: kakushi-pay-indexer
description: Kakushi Pay on Monad - confidential payments (encrypted amounts), pay links, payment requests, payroll, KMS reveals and FHE coprocessor load
contracts:
  - name: KakushiPayToken
    events:
      - event: "Wrapped(address indexed account, uint256 amount)"
      - event: "UnwrapRequested(uint256 indexed requestId, address indexed account)"
      - event: "Unwrapped(uint256 indexed requestId, address indexed account, uint256 amount)"
      - event: "ConfidentialTransfer(address indexed from, address indexed to, bytes32 indexed amount)"
      - event: "Paid(address indexed from, address indexed to, bytes32 amount, bytes32 indexed ref)"
      - event: "LinkCreated(uint256 indexed id, address indexed sender, address claimKey, uint64 expiry, bytes32 amount)"
      - event: "LinkClaimed(uint256 indexed id, address indexed to)"
      - event: "LinkRefunded(uint256 indexed id)"
      - event: "PayrollRun(address indexed employer, address indexed operator, uint256 count, bytes32 indexed ref)"
      - event: "OperatorSet(address indexed holder, address indexed operator, uint48 until)"
      - event: "PaymentRequested(uint256 indexed id, address indexed payee, address indexed payer, uint64 expiry, bytes32 ref, bytes32 due)"
      - event: "RequestPaid(uint256 indexed id, address indexed payer, bytes32 sent)"
      - event: "RequestCancelled(uint256 indexed id)"
  - name: KakushiDecryptionOracle
    events:
      - event: "DecryptionRequested(uint256 indexed requestId, address indexed requester, bytes32[] handles, bytes4 callback)"
      - event: "DecryptionFulfilled(uint256 indexed requestId, uint256[] cleartexts, bool callbackOk, address via)"
  - name: KakushiExecutor
    events:
      - event: "FheOp(uint8 indexed op, bytes32 result, bytes32 lhs, bytes32 rhs, bool scalar, address indexed caller)"
      - event: "FheSelect(bytes32 result, bytes32 control, bytes32 ifTrue, bytes32 ifFalse, address indexed caller)"
      - event: "TrivialEncrypt(bytes32 result, uint256 value, uint8 toType)"
      - event: "VerifyInput(bytes32 result, bytes32 inputHandle, address indexed user, address indexed caller)"
      - event: "Rand(bytes32 result, uint256 upperBound, bytes32 seed, uint8 randType)"
address_format: lowercase
chains:
  - id: ${dep.chainId ?? 10143} # Monad testnet${network === "local" ? " (local anvil fork)" : ""}
    start_block: ${startBlock}
${source}    contracts:
      - name: KakushiPayToken
        address:
${tokens.map((t) => `          - "${t.address}" # ${t.symbol} over ${t.underlyingSymbol}`).join("\n")}
      - name: KakushiDecryptionOracle
        address: "${dep.oracle.toLowerCase()}"
      - name: KakushiExecutor
        address: "${dep.executor.toLowerCase()}"
`;
writeFileSync(`${ROOT}config.yaml`, yaml);

const ts = `// GENERATED by scripts/configure.ts for KAKUSHI_FHE_NETWORK=${network}. Do not edit.
// Static metadata the handlers need (token symbols, the CRE forwarder that marks CRE-delivered reveals).
export const NETWORK = ${JSON.stringify(network)};
export const CRE_FORWARDER = ${JSON.stringify((dep.creForwarder ?? "").toLowerCase())};
export const TOKENS: Record<string, { symbol: string; decimals: number; underlying: string; underlyingSymbol: string }> = ${JSON.stringify(
  Object.fromEntries(tokens.map((t) => [t.address, { symbol: t.symbol, decimals: t.decimals, underlying: t.underlying, underlyingSymbol: t.underlyingSymbol }])),
  null,
  2,
)};
`;
writeFileSync(`${ROOT}src/network.generated.ts`, ts);
console.log(`config.yaml + src/network.generated.ts written for ${network}: start ${startBlock}, tokens ${tokens.map((t) => `${t.symbol}@${t.address}`).join(", ")}, oracle ${dep.oracle}, executor ${dep.executor}`);
