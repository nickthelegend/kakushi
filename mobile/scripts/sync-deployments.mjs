// Copies contract addresses from ../contracts/deployments into src/lib/deployments.ts
// (Metro cannot import files outside the app). Re-run after a redeploy: `npm run sync:deployments`.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "..", "contracts", "deployments");
const read = (f) => (existsSync(join(dir, f)) ? JSON.parse(readFileSync(join(dir, f), "utf8")) : null);
const pick = (core, apps) =>
  core && apps?.causd
    ? { chainId: core.chainId, oracle: core.oracle, acl: core.acl, deployBlock: core.deployBlock, causd: apps.causd, ausd: apps.ausd ?? "0xa9012a055bd4e0eDfF8Ce09f960291C09D5322dC" }
    : null;
const out = { local: pick(read("local.json"), read("local-apps.json")), testnet: pick(read("testnet.json"), read("testnet-apps.json")) };
writeFileSync(
  join(root, "src", "lib", "deployments.ts"),
  `// GENERATED by scripts/sync-deployments.mjs from contracts/deployments/*.json. null = not deployed yet.\n` +
    `export interface Deployment { chainId: number; oracle: \`0x\${string}\`; acl: \`0x\${string}\`; deployBlock: number; causd: \`0x\${string}\`; ausd: \`0x\${string}\` }\n` +
    `export const DEPLOYMENTS: { local: Deployment | null; testnet: Deployment | null } = ${JSON.stringify(out, null, 2)} as never;\n`,
);
console.log("deployments:", JSON.stringify(out));
